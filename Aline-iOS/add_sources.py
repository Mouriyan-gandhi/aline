"""
Keeps the Xcode project in step with the Aline/ folder tree.

The project lists every file explicitly (it was generated by generate_project.py, not a
folder-synced project), so a new file must be registered before it compiles. This script:
  1. arranges file references into nested groups mirroring the folders on disk
     (Aline › Services › Networking › AlineAPI.swift), so Xcode's navigator shows folders;
  2. adds any Swift file under Aline/ the project doesn't reference yet, in its folder's group,
     and to the app target's Sources build phase.

Run after adding Swift files:  python3 Aline-iOS/add_sources.py
Safe to re-run: it changes nothing when the project is already in step.
"""
import hashlib
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
PBX = os.path.join(ROOT, "Aline.xcodeproj", "project.pbxproj")
SOURCES_PHASE = "BE5BBB570FCD470AB9ACCA55"
PRODUCTS_GROUP = "B184B83848DC48998933B26B"


def object_id(seed: str) -> str:
    return hashlib.md5(seed.encode()).hexdigest()[:24].upper()


def quoted(value: str) -> str:
    return f'"{value}"' if re.search(r"[^A-Za-z0-9_./]", value) else value


def file_type(name: str) -> str:
    return {
        ".swift": "sourcecode.swift", ".xcassets": "folder.assetcatalog", ".mp4": "video.mp4",
        ".plist": "text.plist.xml",
    }.get(os.path.splitext(name)[1], "file")


def main() -> None:
    text = open(PBX).read()
    main_group = re.search(r"mainGroup = (\w+);", text).group(1)

    # Every file reference: id -> full repo-relative path (e.g. Aline/Services/AI/OnDeviceAI.swift).
    # A reference already inside the group tree stores only its basename; recover its full path
    # from the tree so the script can be re-run.
    refs: dict[str, str] = {}
    groups = {
        m.group(1): (m.group(2), m.group(3))
        for m in re.finditer(r"\t\t(\w+) (?:/\* [^*]* \*/ )?= \{\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = \(\n(.*?)\t\t\t\);\n(.*?)\t\t\};", text, re.S)
    }

    def walk(group_id: str, prefix: str):
        children, rest = groups[group_id]
        path = re.search(r"path = \"?([^\";]+)\"?;", rest)
        here = f"{prefix}/{path.group(1)}" if path else prefix
        for child in re.findall(r"(\w+) /\*", children):
            if child in groups:
                walk(child, here)
            else:
                m = re.search(rf"\t\t{child} /\* [^*]* \*/ = \{{isa = PBXFileReference;[^}}]*?path = \"?([^\";]+)\"?;", text)
                if m and child not in refs:
                    full = m.group(1) if m.group(1).startswith("Aline/") else f"{here}/{m.group(1)}".lstrip("/")
                    refs[child] = full

    walk(main_group, "")

    # New Swift files on disk
    known = set(refs.values())
    added = []
    for folder, _, files in os.walk(os.path.join(ROOT, "Aline")):
        for name in sorted(files):
            if not name.endswith(".swift"):
                continue
            rel = os.path.relpath(os.path.join(folder, name), ROOT)
            if rel in known:
                continue
            ref_id, build_id = object_id("ref:" + rel), object_id("build:" + rel)
            text = text.replace(
                "/* End PBXBuildFile section */",
                f"\t\t{build_id} /* {name} in Sources */ = {{isa = PBXBuildFile; fileRef = {ref_id} /* {name} */; }};\n"
                "/* End PBXBuildFile section */",
            )
            text = text.replace(
                "/* End PBXFileReference section */",
                f"\t\t{ref_id} /* {name} */ = {{isa = PBXFileReference; lastKnownFileType = sourcecode.swift; "
                f"path = {quoted(rel)}; sourceTree = \"<group>\"; }};\n/* End PBXFileReference section */",
            )
            text = re.sub(
                rf"({SOURCES_PHASE} /\* Sources \*/ = {{\n\t\t\tisa = PBXSourcesBuildPhase;\n\t\t\tbuildActionMask = \d+;\n\t\t\tfiles = \(\n)",
                lambda m: m.group(1) + f"\t\t\t\t{build_id} /* {name} in Sources */,\n",
                text,
            )
            refs[ref_id] = rel
            added.append(rel)

    # File references store only their basename; the folders become groups
    for ref_id, full in refs.items():
        name = os.path.basename(full)
        text = re.sub(
            rf"\t\t{ref_id} /\* [^*]* \*/ = \{{isa = PBXFileReference;([^}}]*?)path = \"?[^\";]+\"?;",
            lambda m: f"\t\t{ref_id} /* {name} */ = {{isa = PBXFileReference;{m.group(1)}path = {quoted(name)};",
            text,
        )
        text = re.sub(rf"({ref_id}) /\* [^*]* \*/", rf"\1 /* {name} */", text)
        text = re.sub(rf"(\w+) /\* {re.escape(full)} in (Sources|Resources) \*/", rf"\1 /* {name} in \2 */", text)

    # Rebuild the group tree from the paths
    tree: dict = {}
    for ref_id, full in refs.items():
        node = tree
        for part in full.split("/")[:-1]:
            node = node.setdefault(part, {})
        node.setdefault("__files__", []).append((os.path.basename(full), ref_id))

    group_defs = []

    def build(node: dict, path: str) -> str:
        group_id = object_id("group:" + path)
        entries = []
        for sub in sorted(k for k in node if k != "__files__"):
            entries.append((sub, build(node[sub], f"{path}/{sub}" if path else sub)))
        entries += sorted(node.get("__files__", []), key=lambda e: e[0].lower())
        children = "".join(f"\t\t\t\t{child} /* {label} */,\n" for label, child in entries)
        name = os.path.basename(path)
        group_defs.append(
            f"\t\t{group_id} /* {name} */ = {{\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = (\n{children}\t\t\t);\n"
            f"\t\t\tpath = {quoted(name)};\n\t\t\tsourceTree = \"<group>\";\n\t\t}};\n"
        )
        return group_id

    top_level = [(name, build(sub, name)) for name, sub in sorted(tree.items()) if name != "__files__"]

    # Drop the old non-main, non-Products groups this script made before, then rewrite the section
    section = re.search(r"/\* Begin PBXGroup section \*/\n(.*?)/\* End PBXGroup section \*/", text, re.S)
    kept = []
    for m in re.finditer(r"\t\t(\w+) (?:/\* [^*]* \*/ )?= \{\n\t\t\tisa = PBXGroup;.*?\n\t\t\};\n", section.group(1), re.S):
        if m.group(1) in (main_group, PRODUCTS_GROUP):
            kept.append(m.group(0))
    main_children = "".join(f"\t\t\t\t{gid} /* {name} */,\n" for name, gid in top_level) + f"\t\t\t\t{PRODUCTS_GROUP} /* Products */,\n"
    kept = [
        re.sub(r"children = \(\n.*?\t\t\t\);", lambda _: f"children = (\n{main_children}\t\t\t);", block, flags=re.S)
        if block.lstrip().startswith(main_group) else block
        for block in kept
    ]
    text = text.replace(section.group(1), "".join(kept) + "".join(group_defs))

    open(PBX, "w").write(text)
    print("\n".join(added) if added else "no new files", "| groups:", len(group_defs))


if __name__ == "__main__":
    main()
